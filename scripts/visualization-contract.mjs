import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
const result = spawnSync("cargo", ["run", "--locked", "--quiet", "-p", "centaeris-core", "--example", "visualization_contract"], { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] });
if (result.status !== 0) process.exit(result.status ?? 1);
const { catalog, cases, instructions } = JSON.parse(result.stdout);
const examples = cases.filter(item => item.valid).slice(0, 2);
const reference = "<!-- Generated by scripts/visualization-contract.mjs from Core. -->\n\n"
  + instructions + "\n\n## Limits\n\n"
  + `JSON: ${catalog.limits.bytes} UTF-8 bytes; nodes: ${catalog.limits.elements}; depth: ${catalog.limits.depth}; each text property: ${catalog.limits.textBytes} UTF-8 bytes.\n`
  + "\nAll properties are literal strings. A root has no parent; every other node has exactly one. Unknown fields, broken references, cycles and unreachable nodes are rejected.\n"
  + examples.map(item => "\n## " + item.name + "\n\n```centaeris_visual\n" + item.source + "\n```\n").join("");
const outputs = [
  ["../system-skills/inline-visualizations/references/catalog.md", reference],
  ["../packages/visualization-react/src/generated.json", JSON.stringify(catalog, null, 2) + "\n"],
  ["../packages/ui/tests/fixtures/visualization-conformance.json", JSON.stringify(cases, null, 2) + "\n"],
  ["../packages/visualization-react/src/generated.ts", "// Generated by scripts/visualization-contract.mjs from the Core catalog.\n" +
    "export type VisualComponentName = " + Object.keys(catalog.components).map(JSON.stringify).join(" | ") + ";\n" +
    "export type VisualIconName = " + catalog.components.Icon.props.name.enum.map(JSON.stringify).join(" | ") + ";\n"],
];
for (const [relative, expected] of outputs) {
  const destination = new URL(relative, import.meta.url);
  if (process.argv.includes("--check")) {
    if (readFileSync(destination, "utf8") !== expected) throw new Error(relative + " is stale; run node scripts/visualization-contract.mjs");
  } else writeFileSync(destination, expected);
}
