import assert from "node:assert/strict";
import test from "node:test";
import { mkdtemp, realpath, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";
import { runBrowser, waitFor } from "./browserHarness.mjs";

test("Inbox and catalogs keep navigation, acknowledged state and usable controls across viewport sizes", async () => {
  const profile = await mkdtemp(join(tmpdir(), "centaeris-catalog-browser-"));
  const server = await createServer({ root: fileURLToPath(new URL("../..", import.meta.url)), server: { port: 0, host: "127.0.0.1" } });
  try {
    await server.listen();
    await runBrowser(`${server.resolvedUrls.local[0]}tests/browser/workspace-catalogs.html?theme=${process.env.CENTAERIS_CATALOG_THEME || "light"}`, { width: 1280, height: 900 }, profile, async ({ evaluate, send, frame }) => {
      const text = value => evaluate(`document.body.textContent.includes(${JSON.stringify(value)})`);
      const click = value => evaluate(`([...document.querySelectorAll('button,a,[role=menuitem]')].find(element => element.textContent.trim() === ${JSON.stringify(value)})).click()`);
      async function capture(name) {
        if (!process.env.CENTAERIS_CATALOG_SCREENSHOT_DIR) return;
        await waitFor(() => evaluate("[...document.querySelectorAll('.catalogDetailView')].every(element => getComputedStyle(element).opacity === '1')"), "settled detail view");
        await frame();
        const { data } = await send("Page.captureScreenshot", { format: "png" });
        await writeFile(join(process.env.CENTAERIS_CATALOG_SCREENSHOT_DIR, `${name}.png`), Buffer.from(data, "base64"));
      }
      await waitFor(() => text("Alex assigned this issue to you."), "Inbox items");
      await evaluate("document.querySelector('.inboxItem').click()");
      await waitFor(() => evaluate("Boolean(document.querySelector('[aria-label=\"Mark as unread\"]:not(:disabled)'))"), "notification detail acknowledged");
      await capture("inbox");
      await click("Open Issues");
      await waitFor(() => text("Check the source permissions and record the result."), "linked Issue");
      await evaluate("document.querySelector('.workBreadcrumb a').click()");
      await waitFor(() => evaluate("Boolean(document.querySelector('[aria-label=\"Archive notification\"]:not(:disabled)'))"), "Inbox selection restored after Issue");
      await evaluate("document.querySelector('[aria-label=\"Archive notification\"]').click()");
      await waitFor(() => evaluate("!document.querySelector('[aria-label=\"Archive notification\"]')"), "archive acknowledged");
      await click("Archived");
      await evaluate("window.catalogFixture = undefined");
      await send("Page.reload");
      await waitFor(() => evaluate("Boolean(window.catalogFixture && document.querySelector('.inboxItem'))"), "reloaded Inbox");
      await waitFor(() => text("Alex assigned this issue to you."), "archived notification after reload");
      await evaluate("document.querySelector('.inboxItem').click()");
      await waitFor(() => evaluate("Boolean(document.querySelector('[aria-label=\"Restore to inbox\"]'))"), "restorable archived notification");
      await evaluate("document.querySelector('[aria-label=\"Restore to inbox\"]').click()");
      await waitFor(() => evaluate(`Boolean(document.querySelector('[aria-label="Archive notification"]:not(:disabled)')) && document.querySelector('[aria-label="Notifications"]')?.getAttribute("aria-busy") === "false" && !document.querySelector(".inboxItem")`), "server-acknowledged empty archive after restore");
      assert.ok(await evaluate(`[...document.querySelectorAll(".inboxTabs button")].some(button => button.textContent === "Archived" && button.getAttribute("aria-pressed") === "true")`), "archive filter retained");
      await evaluate("catalogFixture.navigate('library')");
      await waitFor(() => text("Research brief.pdf"), "Space materials");
      await capture("space");
      await click("New");
      await waitFor(() => evaluate("document.querySelectorAll('[role=menuitem]').length === 4"), "Space creation menu");
      assert.ok(await evaluate("[...document.querySelectorAll('[role=menuitem]')].every((item, index, items) => index === 0 || item.getBoundingClientRect().top >= items[index-1].getBoundingClientRect().bottom)"), "menu actions occupy separate rows");
      await capture("space-create-menu");
      await click("Upload files");
      await waitFor(() => evaluate("Boolean(document.querySelector('[role=dialog]'))"), "upload dialog");
      await click("Cancel");
      await click("Review notes");
      await waitFor(() => evaluate("Boolean(document.querySelector('.libraryFileView textarea'))"), "same-area note editor");
      assert.equal(await evaluate("document.querySelector('.libraryFileView textarea').value"), "Review the evidence before publishing.");
      assert.ok(await evaluate("Boolean(document.querySelector('.libraryRow'))"), "directory remains mounted while editing");
      await capture("space-note");
      await evaluate("document.querySelector('.catalogBack').click()");
      await waitFor(() => evaluate("!document.querySelector('.libraryFileView')"), "returned to materials");
      await click("Workspace sources");
      await waitFor(() => text("Research documents"), "authorized sources");
      await evaluate("[...document.querySelectorAll('.catalogRows a')].find(a => a.textContent.includes('Research documents')).click()");
      await waitFor(() => text("Research brief.pdf"), "source contents");
      await evaluate("catalogFixture.back()");
      await waitFor(() => text("Can view"), "source list history");
      await evaluate("catalogFixture.navigate('work/home')");
      await waitFor(() => text("Workspace resources"), "Home resources");
      await evaluate("window.catalogFixture = undefined");
      await send("Page.reload");
      await waitFor(() => text("Workspace resources"), "Home resources after reload");
      await capture("home");
      await evaluate("[...document.querySelectorAll('.catalogRows a')].find(a => a.textContent.includes('Manage connections')).click()");
      await waitFor(() => text("Credentials required"), "connection status");
      assert.equal(await evaluate("document.querySelectorAll('.connectionCatalog .catalogRows a').length"), 1, "one MCP entry for the plugin");
      await capture("connections");
      await evaluate("document.querySelector('.connectionCatalog .catalogRows a').click()");
      await waitFor(() => evaluate("Boolean(document.querySelector('input[type=password]'))"), "existing credential controls");
      assert.equal(await evaluate("document.querySelector('input[type=password]').value"), "");
      await capture("plugin-detail");
      assert.ok(await evaluate("Boolean(document.querySelector('.connectionCatalog .catalogRows'))"), "connection directory remains mounted");
      assert.ok(await evaluate("document.querySelector('.catalogDetailView').textContent.includes('Document service') && document.querySelector('.catalogDetailView').textContent.includes('Search service')"), "all MCP services are expanded in the detail");
      assert.equal(await evaluate("document.querySelectorAll('.catalogDetailView input[type=password]').length"), 1, "shared credentials are configured once");
      assert.equal(await evaluate("document.querySelectorAll('.catalogDetailView [role=switch]').length"), 0, "connection details do not change plugin enablement");
      await evaluate("document.querySelector('.catalogBack').click()");
      await waitFor(() => evaluate("!document.querySelector('.catalogDetailView')"), "returned to connections");
      await click("Skills");
      await waitFor(() => text("Evidence review"), "skills");
      await capture("skills");
      await evaluate("document.querySelector('.catalogDirectory .catalogRows a').click()");
      await waitFor(() => text("Compare each claim with its source before drawing a conclusion."), "inline skill document");
      await capture("skill-detail");
      await evaluate("document.querySelector('.catalogBack').click()");
      await waitFor(() => evaluate("!document.querySelector('.catalogDetailView')"), "returned to skills");
      await click("Installed");
      await waitFor(() => text("Research tools"), "installed plugins");
      assert.equal(await evaluate("document.querySelectorAll('.pluginSettings input[type=file]').length"), 1);
      await capture("plugins");
      await send("Emulation.setDeviceMetricsOverride", { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
      await evaluate("catalogFixture.navigate('work/inbox')");
      await waitFor(() => text("Alex assigned this issue to you."), "narrow Inbox");
      await evaluate("document.querySelector('.inboxItem').click()");
      await waitFor(() => evaluate("Boolean(document.querySelector('[aria-label=\"Close notification\"]'))"), "narrow notification detail");
      await capture("inbox-mobile");
      assert.ok(await evaluate("document.documentElement.scrollWidth <= innerWidth"), "no horizontal viewport overflow");
      await evaluate("document.querySelector('[aria-label=\"Close notification\"]').click()");
      await waitFor(() => evaluate("document.querySelector('.inboxItem').getBoundingClientRect().width > 0"), "return to narrow list");
      await evaluate("catalogFixture.language('zh-CN'); catalogFixture.navigate('extensions?view=connections')");
      await waitFor(() => text("需要凭证"), "translated connections");
      await capture("connections-mobile");
      assert.ok(await evaluate("document.documentElement.scrollWidth <= innerWidth"), "narrow catalog fits viewport");
      await evaluate("document.querySelector('.connectionCatalog .catalogRows a').click()");
      await waitFor(() => evaluate("Boolean(document.querySelector('input[type=password]'))"), "narrow credential form");
      assert.ok(await evaluate("document.documentElement.scrollWidth <= innerWidth"), "credential form fits viewport");
      await capture("plugin-mobile");
      await evaluate("catalogFixture.language('en'); catalogFixture.navigate('work/tasks')");
      await waitFor(() => text("Review evidence for the connector integration"), "API-backed issue list");
      await evaluate("document.querySelector('.issueRow').click()");
      await waitFor(() => text("Check the source permissions and record the result."), "Issue detail");
      assert.ok(await evaluate("document.documentElement.scrollWidth <= innerWidth"), "Issue detail fits narrow viewport");
      await capture("issue-mobile");
      await send("Page.reload");
      await waitFor(() => evaluate("Boolean(window.catalogFixture && document.querySelector('.issueDetail'))"), "reloaded Issue URL");
      await waitFor(() => text("Check the source permissions and record the result."), "Issue refetched after reload");
      await evaluate("document.querySelector('.workBreadcrumb a').click()");
      await waitFor(() => evaluate("Boolean(document.querySelector('.issueRow'))"), "returned to Issues list");
      assert.deepEqual(await evaluate("catalogFixture.failures"), []);
    });
  } finally {
    await server.close();
    const resolved = await realpath(profile);
    assert.equal(dirname(resolved), await realpath(tmpdir()));
    assert.ok(basename(resolved).startsWith("centaeris-catalog-browser-"));
    await rm(resolved, { recursive: true, force: true });
  }
});
